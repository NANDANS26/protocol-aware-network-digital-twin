std::string sha256_hex(std::span<const uint8_t> data) {
    uint32_t h0 = 0x6a09e667;
    uint32_t h1 = 0xbb67ae85;
    uint32_t h2 = 0x3c6ef372;
    uint32_t h3 = 0xa54ff53a;
    uint32_t h4 = 0x510e527f;
    uint32_t h5 = 0x9b05688c;
    uint32_t h6 = 0x1f83d9ab;
    uint32_t h7 = 0x5be0cd19;

    uint64_t total_bits = data.size() * 8ULL;

    std::vector<uint8_t> msg(data.begin(), data.end());
    msg.push_back(0x80);
    while ((msg.size() % 64) != 56) {
        msg.push_back(0x00);
    }
    for (int i = 7; i >= 0; --i) {
        msg.push_back(static_cast<uint8_t>((total_bits >> (i * 8)) & 0xff));
    }

    for (size_t chunk = 0; chunk < msg.size(); chunk += 64) {
        std::array<uint32_t, 64> w{};
        for (size_t t = 0; t < 16; ++t) {
            size_t off = chunk + t * 4;
            w[t] = (static_cast<uint32_t>(msg[off]) << 24) |
                   (static_cast<uint32_t>(msg[off + 1]) << 16) |
                   (static_cast<uint32_t>(msg[off + 2]) << 8) |
                    static_cast<uint32_t>(msg[off + 3]);
        }
        for (size_t t = 16; t < 64; ++t) {
            w[t] = theta1(w[t - 2]) + w[t - 7] + theta0(w[t - 15]) + w[t - 16];
        }

        uint32_t a = h0;
        uint32_t b = h1;
        uint32_t c = h2;
        uint32_t d = h3;
        uint32_t e = h4;
        uint32_t f = h5;
        uint32_t g = h6;
        uint32_t h = h7;

        for (size_t t = 0; t < 64; ++t) {
            uint32_t t1 = h + sig1(e) + choose(e, f, g) + K[t] + w[t];
            uint32_t t2 = sig0(a) + majority(a, b, c);
            h = g;
            g = f;
            f = e;
            e = d + t1;
            d = c;
            c = b;
            b = a;
            a = t1 + t2;
        }

        h0 += a;
        h1 += b;
        h2 += c;
        h3 += d;
        h4 += e;
        h5 += f;
        h6 += g;
        h7 += h;
    }

    std::ostringstream oss;
    const std::array<uint32_t, 8> digest = {h0, h1, h2, h3, h4, h5, h6, h7};
    for (uint32_t val : digest) {
        oss << std::hex << std::setw(8) << std::setfill('0') << val;
    }
    return oss.str();
}

